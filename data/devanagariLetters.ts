function buildDevanagariLessons(
  letters: DevanagariLetter[],
  language: "hindi" | "marathi",
): LetterLesson[] {
  return letters.map(({ char, tr }) => {
    const examples = EXAMPLE_WORDS[char];
    const isHindi = language === "hindi";

    const word1 = isHindi ? examples.hindi1 : examples.marathi1;
    const word1Tr = isHindi ? examples.hindi1Tr : examples.marathi1Tr;
    const word2 = isHindi ? examples.hindi2 : examples.marathi2;
    const word2Tr = isHindi ? examples.hindi2Tr : examples.marathi2Tr;

    const usage = isHindi ? `${char} से ${word1}।` : `${char} - ${word1}`;
    const usageTransliteration = isHindi
      ? `${tr} se ${word1Tr}`
      : `${tr} - ${word1Tr}`;

    return {
      word: char,
      transliteration: tr,
      emoji: examples.emoji1,
      usage,
      usageTransliteration,
      examples: [
        {
          emoji: examples.emoji1,
          text: isHindi ? `${char} से ${word1}।` : `${char} - ${word1}`,
          transliteration: isHindi
            ? `${tr} se ${word1Tr}`
            : `${tr} - ${word1Tr}`,
        },
        {
          emoji: examples.emoji2,
          text: isHindi ? `${char} से ${word2}।` : `${char} - ${word2}`,
          transliteration: isHindi
            ? `${tr} se ${word2Tr}`
            : `${tr} - ${word2Tr}`,
        },
      ],
    };
  });
}

export function getDevanagariLetterSet(
  topicId: DevanagariHubTopicId,
): DevanagariLetter[] {
  if (topicId === "swar") {
    return DEVANAGARI_SWAR;
  }

  if (topicId === "vyanjan") {
    return DEVANAGARI_VYANJAN;
  }

  return DEVANAGARI_AKSHAR;
}

export function getDevanagariLessons(
  topicId: DevanagariHubTopicId,
  language: "hindi" | "marathi",
): LetterLesson[] {
  return buildDevanagariLessons(getDevanagariLetterSet(topicId), language);
}

export function getDevanagariLetterCount(topicId: DevanagariHubTopicId): number {
  return getDevanagariLetterSet(topicId).length;
}

export function isDevanagariHubTopicId(
  topicId: string,
): topicId is DevanagariHubTopicId {
  return (DEVANAGARI_HUB_TOPIC_IDS as readonly string[]).includes(topicId);
}
