const sourceLessons = JSON.parse(readFileSync(SOURCE, "utf8"));

const lessons = sourceLessons.map((lesson) => {
  const { emoji, examples } = buildExamples(
    lesson.word,
    lesson.example,
    SIGHT_WORD_EMOJIS,
    "👁️",
    lesson.meaning,
    lesson.usage,
    SIGHT_WORD_EXTRAS[lesson.word] ?? [],
  );

  return {
    word: lesson.word,
    emoji,
    meaning: lesson.meaning,
    usage: lesson.usage,
    examples,
  };
});

writeFileSync(OUTPUT, `${JSON.stringify(lessons, null, 2)}\n`);
console.log(`Wrote ${lessons.length} sight word lessons.`);
